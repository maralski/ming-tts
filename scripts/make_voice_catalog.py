"""Writes Sources/MingTTS/Text/MingVoiceCatalog.swift from the reference cookbook's voice tables.

    python3 scripts/make_voice_catalog.py MING_CODE/cookbooks/instruction_en.md

MING_CODE is a checkout of the inclusionAI Ming repository.
"""
import os, re, sys

source = os.path.expanduser(sys.argv[1])
text = open(source, encoding="utf-8").read()
section = text[text.index('## <a id="built-in-premium-voices">'):text.index('## <a id="voice-design">')]
names = []
for line in section.splitlines():
    if not line.startswith("| ") or line.startswith("| :"):
        continue
    cells = [c.strip() for c in line.strip("|").split("|")]
    if m := re.fullmatch(r"`([^`]+)`", cells[0]):
        names.append(m[1])
    if len(cells) == 7:  # the emotion-variant table names each variant in its last column
        names += re.findall(r"`([^`]+)`", cells[-1])
assert len(names) == len(set(names)), "duplicate voice"
body = ",\n".join(f'        "{n}"' for n in names)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../Sources/MingTTS/Text/MingVoiceCatalog.swift")
open(out, "w", encoding="utf-8").write(f"""// Copyright 2026 Peter Marelas
// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/make_voice_catalog.py from the reference cookbooks/instruction_en.md.

extension MingVoice {{
    /// Every built-in voice in the reference cookbook, by `ip` name: Chinese voices, Chinese
    /// emotion variants (`<voice>_<emotion>`), then the English voices.
    public static let catalog: [MingVoice] = [
{body},
    ].map {{ MingVoice(ip: $0) }}
}}
""")
print(len(names), "voices")
